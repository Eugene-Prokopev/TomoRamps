def apply_patches() -> int:
    errors, applied, skipped = [], 0, 0
    patched = {}
    for fname, patches in (("Configuration.h", PATCHES_H), ("Configuration_adv.h", PATCHES_ADV)):
        path = MARLIN_DIR / "Marlin" / fname
        text = original = path.read_text(encoding="utf-8")
        for item in patches:
            pattern, repl, desc = item[0], item[1], item[2]
            allow_append = len(item) > 3 and item[3] == "APPEND"
            new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
            if n:
                text = new
                applied += 1
                print(f"  [patch] {desc}")
                continue
            # Р РЋРЎвЂњР В Р’В¶Р В Р’Вµ Р В РЎвЂ”Р РЋР вЂљР В РЎвЂР В РЎВР В Р’ВµР В Р вЂ¦Р В Р’ВµР В Р вЂ¦Р В РЎвЂў Р РЋР вЂљР В Р’В°Р В Р вЂ¦Р В Р’ВµР В Р’Вµ? (Р В РЎвЂўР РЋРІР‚С™Р РЋР С“Р РЋРІР‚С™Р РЋРЎвЂњР В РЎвЂ” Р В РЎвЂ Р РЋРІР‚В¦Р В Р вЂ Р В РЎвЂўР РЋР С“Р РЋРІР‚С™Р В РЎвЂўР В Р вЂ Р В РЎвЂўР В РІвЂћвЂ“ Р В РЎвЂќР В РЎвЂўР В РЎВР В РЎВР В Р’ВµР В Р вЂ¦Р РЋРІР‚С™Р В Р’В°Р РЋР вЂљР В РЎвЂР В РІвЂћвЂ“ Р В Р вЂ¦Р В Р’Вµ Р В Р вЂ Р В Р’В°Р В Р’В¶Р В Р вЂ¦Р РЋРІР‚в„–)
            if re.search(r"^\s*" + re.escape(repl) + r"(?:\s|$)", text, flags=re.M):
                skipped += 1
                print(f"  [skip ] {desc} (Р РЋРЎвЂњР В Р’В¶Р В Р’Вµ Р В РЎвЂ”Р РЋР вЂљР В РЎвЂР В РЎВР В Р’ВµР В Р вЂ¦Р В Р’ВµР В Р вЂ¦Р В РЎвЂў)")
                continue
            if allow_append:
                text += f"\n#define {repl.split(None, 1)[1]}  // TomoRamps: {desc}\n"
                applied += 1
                print(f"  [add  ] {desc} (Р В РўвЂР В РЎвЂўР В Р’В±Р В Р’В°Р В Р вЂ Р В Р’В»Р В Р’ВµР В Р вЂ¦Р В РЎвЂў Р В Р вЂ  Р В РЎвЂќР В РЎвЂўР В Р вЂ¦Р В Р’ВµР РЋРІР‚В  Р РЋРІР‚С›Р В Р’В°Р В РІвЂћвЂ“Р В Р’В»Р В Р’В°)")
                continue
            errors.append(f"{fname}: Р В Р вЂ¦Р В Р’Вµ Р В Р вЂ¦Р В Р’В°Р В РІвЂћвЂ“Р В РўвЂР В Р’ВµР В Р вЂ¦Р В РЎвЂў '{pattern}' ({desc})")
        patched[path] = (text, original)
    if errors:
        print("\n[Р В РЎвЂєР В Р РѓР В Р’ВР В РІР‚ВР В РЎв„ўР В Р’В] Р В РЎСџР В Р’В°Р РЋРІР‚С™Р РЋРІР‚РЋР В РЎвЂ Р В Р вЂ¦Р В Р’Вµ Р В РЎвЂ”Р РЋР вЂљР В РЎвЂР В РЎВР В Р’ВµР В Р вЂ¦Р В РЎвЂР В Р’В»Р В РЎвЂР РЋР С“Р РЋР Р‰ (Р РЋРІР‚С›Р В Р’В°Р В РІвЂћвЂ“Р В Р’В» Р В РЎСљР В РІР‚Сћ Р В РЎвЂР В Р’В·Р В РЎВР В Р’ВµР В Р вЂ¦Р РЋРІР‚ВР В Р вЂ¦):")
        for e in errors:
            print("  -", e)
        return 1
    for path, (text, original) in patched.items():
        if text != original:
            path.write_text(text, encoding="utf-8", newline="\n")
    print(f"\n[ok] Р В РЎСџР В Р’В°Р РЋРІР‚С™Р РЋРІР‚РЋР В Р’ВµР В РІвЂћвЂ“ Р В РЎвЂ”Р РЋР вЂљР В РЎвЂР В РЎВР В Р’ВµР В Р вЂ¦Р В Р’ВµР В Р вЂ¦Р В РЎвЂў/Р В РЎвЂ”Р РЋР вЂљР В РЎвЂўР В Р вЂ Р В Р’ВµР РЋР вЂљР В Р’ВµР В Р вЂ¦Р В РЎвЂў: {applied + skipped}")
    return 0


